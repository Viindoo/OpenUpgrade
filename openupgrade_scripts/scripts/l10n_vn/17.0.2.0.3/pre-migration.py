def _vn_coa_rename_xml_id(env):
    """
    Since the removal of account.chart.template
    we need to rename some xml_id like tax or tax.group
    in order to avoid duplication
    """
    env.cr.execute("""SELECT id FROM res_company WHERE chart_template = 'vn'""")
    xmlids_renames = []
    data_xmlid_to_rename = []
    data_xmlid_to_rename.extend(_account_tax_group_xmlid)
    data_xmlid_to_rename.extend(_account_tax_xmlid)
    data_xmlid_to_rename.extend(_account_account_xmlid)
    company_ids = [r[0] for r in env.cr.fetchall()]
    for company_id in company_ids:
        for xmlid in data_xmlid_to_rename:
            if (
                env["account.chart.template"]
                .with_company(company_id)
                .ref(xmlid, raise_if_not_found=False)
            ):
                continue
            old_xmlid = f"l10n_vn.{company_id}_{xmlid}"
            new_xmlid = f"account.{company_id}_{xmlid}"
            xmlids_renames.append((old_xmlid, new_xmlid))
    openupgrade.rename_xmlids(env.cr, xmlids_renames)


